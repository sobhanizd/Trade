interface Msg { q: string; a: string; model?: string; mode?: string; missing?: string[]; note?: string }

export function Chat({ symbols, initialSymbol, signalId, aiEnabled, history }: { symbols: string[]; initialSymbol?: string; signalId?: string; aiEnabled: boolean; history: { q: string; a: string; model: string; at: string }[] }) {
  const t = useL(L);
  const locale = useLocale();
  const [symbol, setSymbol] = useState(initialSymbol ?? "");
  const [q, setQ] = useState("");
  const [msgs, setMsgs] = useState<Msg[]>(history.map((h) => ({ q: h.q, a: h.a, model: h.model, mode: "ai" })));
  const [busy, setBusy] = useState(false);
  const [err, setErr] = useState<string | null>(null);

  async function ask(question: string) {
    if (question.trim().length < 3) return;
    setBusy(true);
    setErr(null);
    try {
      const r = await api<{ answer: string; mode: string; model?: string; missing?: string[]; note?: string }>("/api/ai/ask", {
        body: { question, symbol: symbol || undefined, signalId: signalId || undefined },
      });
      setMsgs((m) => [...m, { q: question, a: r.answer, model: r.model, mode: r.mode, missing: r.missing, note: r.note }]);
      setQ("");
    } catch (e) {
      setErr(errorText((e as Error).message, locale));
    } finally {
      setBusy(false);
    }
  }

  return (
    <div className="grid gap-4 lg:grid-cols-3">
      <Card className="lg:col-span-2">
        <div className="mb-3 flex flex-wrap items-center gap-2">
          {signalId ? <Badge tone="accent">{t.focused(signalId.slice(0, 8))}</Badge> : (
            <Select value={symbol} onChange={(e) => setSymbol(e.target.value)} className="max-w-48" aria-label={t.assetContext}>
              <option value="">{t.allAssets}</option>
              {symbols.map((s) => <option key={s}>{s}</option>)}
            </Select>
          )}
          <Badge>{aiEnabled ? t.aiMode : t.ruleMode}</Badge>
        </div>
        <div className="space-y-4" aria-live="polite">
          {msgs.length === 0 && <p className="text-sm text-ink-2">{t.empty}</p>}
          {msgs.map((m, i) => (
            <div key={i} className="space-y-2">
              <div className="ms-auto max-w-[85%] rounded-lg bg-accent/10 px-3 py-2 text-sm" dir="auto">{m.q}</div>
              <div className="rounded-lg border border-line px-3 py-2 text-sm whitespace-pre-wrap" dir="auto">{m.a}</div>
              <div className="text-xs text-ink-2">
                {m.mode === "deterministic" ? t.ruleBased : t.generatedBy(m.model ?? "AI")}
                {m.note ? ` ${m.note}` : ""}
                {m.missing && m.missing.length > 0 && <> {t.missing} {m.missing.join(" ")}</>}
              </div>
            </div>
          ))}
          {busy && <p className="text-sm text-ink-2">{t.thinking}</p>}
        </div>
        {err && <Alert tone="error" className="mt-3">{err}</Alert>}
        <form className="mt-4 flex gap-2" onSubmit={(e) => { e.preventDefault(); void ask(q); }}>
          <textarea value={q} onChange={(e) => setQ(e.target.value)} maxLength={1000} rows={2} placeholder={t.placeholder} aria-label={t.yourQuestion} dir="auto" className="min-h-10 flex-1 rounded-lg border border-line bg-surface px-3 py-2 text-sm focus:border-accent focus:outline-none" />
          <Button type="submit" disabled={busy || q.trim().length < 3}>{t.ask}</Button>
        </form>
      </Card>
      <Card>
        <h2 className="mb-2 text-sm font-semibold">{t.examples}</h2>
        <ul className="space-y-1.5">
          {t.presets.map((p) => (
            <li key={p}><button disabled={busy} onClick={() => ask(p)} className="text-start text-sm text-accent hover:underline disabled:opacity-50">{p}</button></li>
          ))}
        </ul>
        <p className="mt-4 text-xs text-ink-2">{t.privacy}</p>
      </Card>
    </div>
  );
}
